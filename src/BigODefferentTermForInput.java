public class BigODefferentTermForInput
{
    public static void printItem(int a,int b) {
        for (int i = 0; i < a; i++)
        {
            System.out.println(i);
        }
        for (int i=0;i<b;i++)
        {
            System.out.println(i);
        }
    }

    public static void main(String[] args) {
        printItem(1,2);

    }
}
